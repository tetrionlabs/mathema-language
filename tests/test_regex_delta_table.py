"""The regex delta table the package ships (`text/data/regex_deltas.json`,
generated by `tests/_regex_delta_data.py`) is what this interpreter
reads: each row for this Python carries the digest of this
interpreter's reading. Every construct the term's translation names is
in the table, and the table is keyed by construct, dialect and
version."""
import json
import re
import sys

import pytest

from mathema_language.text import _regular
from tests import _regex_delta_data as generator

TABLE = _regular.regex_deltas()
HERE = f"{sys.version_info[0]}.{sys.version_info[1]}"


def _dump_here(tmp_path):
    path = tmp_path / "here.json"
    generator.dump(str(path))
    return json.loads(path.read_text())["readings"]


def test_the_table_covers_every_supported_python_and_probe():
    assert TABLE["versions"] == _regular.versions_data()["versions"]
    named = set(TABLE["read_alike"]) | {r["construct"] for r in TABLE["rows"]}
    assert named == set(generator.PROBES)
    for row in TABLE["rows"]:
        assert set(row) == {"construct", "dialect", "version", "reads", "digest"}
        assert row["dialect"] == "python" and row["version"] in TABLE["versions"]


def test_this_interpreter_reads_each_construct_as_the_table_says(tmp_path):
    if HERE not in TABLE["versions"]:
        pytest.skip(f"python {HERE} is not a supported version")
    readings = _dump_here(tmp_path)
    rows = {(r["construct"], r["version"]): r for r in TABLE["rows"]}
    for construct, reading in readings.items():
        if construct not in TABLE["read_alike"]:
            assert rows[(construct, HERE)]["digest"] == reading["digest"], construct


def test_every_construct_the_translation_names_is_in_the_table():
    named = set(TABLE["read_alike"]) | {r["construct"] for r in TABLE["rows"]}
    assert set(_regular._CONSTRUCTS.values()) <= named
    assert set(_regular._POSITIONS.values()) <= named
    assert set(_regular._FLAG_CONSTRUCTS.values()) <= named
    assert set(TABLE["translated"]) <= named


@pytest.mark.parametrize("pattern, flags, used", [
    (r"(?im)^a\Z", 0, {"inline flags at the start", "ignore case", "multi line", "start of line",
                       "end of text", "literal"}),
    (r"(?<=a)(?!b)[^cd]+?", 0, {"lookbehind", "lookahead", "character set", "lazy repeat",
                                "literal"}),
    (r"(a)?(?(1)b|c)|\1", re.VERBOSE, {"group", "greedy repeat", "literal", "conditional",
                                       "alternation", "backreference", "verbose"}),
    (r"(?i:a)\Bb", 0, {"group", "scoped flags", "ignore case", "literal", "not a word boundary"}),
])
def test_the_constructs_of_a_pattern_are_read_from_its_parse_and_its_text(pattern, flags, used):
    assert _regular.constructs(pattern, flags) == used


@pytest.mark.skipif(sys.version_info >= (3, 11), reason="3.11 and later refuse the pattern")
def test_global_flags_after_the_start_are_read_from_the_text():
    assert "inline flags after the start" in _regular.constructs("a(?i)b")
